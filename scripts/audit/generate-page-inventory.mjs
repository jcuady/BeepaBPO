/**
 * Generates docs/PAGE_INVENTORY.md from the App Router tree.
 *
 * For every route under app/ it records: the path, whether it is a page or a
 * route handler, the RBAC gates it declares, the server actions it calls, and
 * the client components it renders. This is the map Phase G needs to bound a
 * per-page functional review — you cannot audit "every page" without first
 * knowing how many there are and what each one claims to do.
 *
 * Run:  node scripts/audit/generate-page-inventory.mjs [--check]
 * --check exits non-zero if the committed file is stale, so drift is visible
 * in CI rather than discovered later.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = process.cwd();
const OUT = join(ROOT, "docs/PAGE_INVENTORY.md");
const SKIP = new Set(["node_modules", ".next", ".git"]);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function routeFor(file) {
  const rel = relative(join(ROOT, "app"), file).replace(/\\/g, "/");
  const m = rel.match(/^(.*)\/(page|route)\.tsx?$/);
  if (!m) return null;
  const [, slug, kind] = m;
  // Route groups are not part of the URL: app/(marketing)/about -> /about.
  const segments = slug
    .split("/")
    .filter((s) => s && !/^\(.*\)$/.test(s))
    .map((s) => (s.startsWith("[") ? ":" + s.replace(/^\[|\]$/g, "") : s));
  const path = "/" + segments.join("/");
  return { path: path.replace(/\/$/, "") || "/", kind, slug };
}

const GATE = /\b(requirePermission|requireInternal|requireAnyPermission|canAny|can|redirect)\s*\(\s*[^)]*?"([a-z]+\.[a-z]+)"/g;
const ACTION = /from\s+"@\/lib\/([a-z]+)\/actions"/g;
const SERVER_ACTION = /await\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(/g;

const pages = [];
const routes = [];

for (const file of walk(join(ROOT, "app"))) {
  const info = routeFor(file);
  if (!info) continue;
  const src = readFileSync(file, "utf8");
  const gates = [...new Set([...src.matchAll(GATE)].map((m) => m[2]))].sort();
  const actionMods = [...new Set([...src.matchAll(ACTION)].map((m) => m[1]))].sort();
  const entry = {
    ...info,
    file: relative(ROOT, file).replace(/\\/g, "/"),
    gates,
    actionMods,
    dynamic: /^"|^'/.test(info.slug) || info.slug.includes("["),
  };
  (info.kind === "page" ? pages : routes).push(entry);
}

pages.sort((a, b) => a.path.localeCompare(b.path));
routes.sort((a, b) => a.path.localeCompare(b.path));

const md = [];
md.push("# Page Inventory");
md.push("");
md.push("> Generated by `node scripts/audit/generate-page-inventory.mjs`. Do not hand-edit.");
md.push("> Re-run after adding or removing a route; `--check` fails if this file is stale.");
md.push("");
md.push(`${pages.length} page(s) and ${routes.length} route handler(s) under \`app/\`.`);
md.push("");
md.push("**Gates** are the permission codes the route checks itself with");
md.push("(`requirePermission`, `can`, and similar). A route with no listed gate is either");
md.push("public or protected only by its parent layout; verify before assuming it is safe.");
md.push("");
md.push("## Pages");
md.push("");
md.push("| Path | Gates | Server actions | Source |");
md.push("| --- | --- | --- | --- |");
for (const p of pages) {
  md.push(
    `| \`${p.path}\` | ${p.gates.length ? p.gates.map((g) => `\`${g}\``).join(", ") : "-"} | ` +
      `${p.actionMods.length ? p.actionMods.map((a) => `\`${a}\``).join(", ") : "-"} | ` +
      `\`${p.file}\` |`,
  );
}
md.push("");
md.push("## Route handlers");
md.push("");
md.push("| Path | Gates | Source |");
md.push("| --- | --- | --- |");
for (const r of routes) {
  md.push(
    `| \`${r.path}\` | ${r.gates.length ? r.gates.map((g) => `\`${g}\``).join(", ") : "-"} | \`${r.file}\` |`,
  );
}
md.push("");
md.push("## How to use this");
md.push("");
md.push("This is the bounded surface for a per-page functional review. For each row:");
md.push("");
md.push("1. Sign in as a role that can reach the route and confirm it renders.");
md.push("2. Confirm the gate column matches what the role should be allowed to do.");
md.push("3. Exercise every control on the page and confirm it reaches a real workflow.");
md.push("4. Confirm the server action it calls is itself authorized in `lib/**/actions.ts`.");
md.push("");
md.push("`scripts/audit/audit-page-wiring.mjs` covers step 3 statically (dead buttons,");
md.push("unsubmittable forms, links to missing routes) and currently reports zero candidates.");
md.push("`scripts/audit/audit-rbac.mjs` and `audit-action-rbac.mjs` cover steps 2 and 4.");
md.push("");

const content = md.join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== content) {
    console.error("docs/PAGE_INVENTORY.md is stale. Re-run without --check.");
    process.exit(1);
  }
  console.log("docs/PAGE_INVENTORY.md is up to date.");
} else {
  writeFileSync(OUT, content, "utf8");
  console.log(`Wrote docs/PAGE_INVENTORY.md — ${pages.length} pages, ${routes.length} handlers.`);
}