import type { Metadata, Viewport } from "next";
import { DM_Sans, Instrument_Serif, Inter, Manrope } from "next/font/google";
import { BRAND } from "@/lib/site";
import "./globals.css";

const manrope = Manrope({
  variable: "--font-manrope",
  subsets: ["latin"],
  weight: ["500", "600", "700"],
  display: "swap",
});

/**
 * Body face for the landing page only.
 *
 * The landing page is a direct port of the "BeepaBPO new landing design"
 * reference, which sets its body copy in DM Sans. The variable is applied
 * strictly inside `.beepaLanding` (see components/landing/landing.css), so
 * every other route keeps Inter for body and Manrope for display.
 */
const dmSans = DM_Sans({
  variable: "--font-dm-sans",
  subsets: ["latin"],
  weight: ["400", "500", "600"],
  display: "swap",
});

/**
 * Editorial display serif — hero headlines and pull-quotes only.
 * Keeps the sans (Manrope/Inter) for body, UI, labels, and buttons so the
 * product stays legible; the serif is a single, deliberate accent that gives
 * the marketing hero its premium editorial voice.
 */
const instrumentSerif = Instrument_Serif({
  variable: "--font-instrument",
  subsets: ["latin"],
  weight: "400",
  style: ["normal", "italic"],
  display: "swap",
});

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
  weight: ["400", "500", "600"],
  display: "swap",
});

